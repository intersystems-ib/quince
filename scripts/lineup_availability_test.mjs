import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../rugby-frontend/package.json',import.meta.url));
const ts=require('typescript');
const source=await readFile(new URL('../rugby-frontend/src/lineupAvailability.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {availableBench,selectLineupPlayer,swapLineupPlayers,lineupMorale}=await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const players=Array.from({length:23},(_,n)=>({id:`p${n+1}`,available:![0,15,16].includes(n)}));
const initial={id:'lineup',slots:players.slice(0,15).map((p,i)=>({position:i+1,playerId:p.id})),bench:players.slice(15).map(p=>p.id),captainId:'p16'};
const original=JSON.stringify(initial),clean=availableBench(initial,players);
assert.deepEqual(clean.bench,['p18','p19','p20','p21','p22','p23']);
assert.equal(clean.captainId,'p2');assert.equal(JSON.stringify(initial),original);
assert.equal(availableBench(clean,players),clean);
const replacement=selectLineupPlayer(clean,players,{kind:'starter',index:0},'p18');
assert.equal(replacement.slots[0].playerId,'p18');assert.equal(replacement.bench.length,5);
assert.ok(!replacement.bench.includes('p1'));
assert.equal(new Set([...replacement.slots.map(s=>s.playerId),...replacement.bench]).size,20);
assert.deepEqual(players.filter(p=>!p.available&&!replacement.slots.some(s=>s.playerId===p.id)).map(p=>p.id),['p1','p16','p17']);
assert.equal(selectLineupPlayer(clean,players,{kind:'starter',index:0},'p16'),clean);
assert.equal(selectLineupPlayer(clean,players,{kind:'starter',index:0},'p2'),clean);
const swap=selectLineupPlayer(clean,players,{kind:'starter',index:1},'p19');
assert.equal(swap.slots[1].playerId,'p19');assert.ok(swap.bench.includes('p2'));
const captainReplacement=selectLineupPlayer({...clean,captainId:'p1'},players,{kind:'starter',index:0},'p20');
assert.equal(captainReplacement.captainId,'p20');
const recovered=players.map(p=>({...p,available:true}));
assert.deepEqual(availableBench(replacement,recovered).bench,replacement.bench);
console.log('PASS unavailable bench and captain cleanup, immutable inputs, stable refresh, injured starter replacement, healthy swaps, blocked unavailable selection, no vacant starter swaps, recovered players not auto-selected');

const healthy=Array.from({length:25},(_,i)=>({id:`h${i+1}`,available:true,position:(i%15)+1,secondary:[],morale:73}));
const lineup={slots:healthy.slice(0,15).map((p,i)=>({position:i+1,playerId:p.id})),bench:healthy.slice(15,23).map(p=>p.id),captainId:'h1'};
const swapped=swapLineupPlayers(lineup,healthy,{kind:'starter',index:0},{kind:'starter',index:9});
assert.equal(swapped.slots[0].playerId,'h10');assert.equal(swapped.slots[9].playerId,'h1');
assert.equal(lineupMorale(healthy[0],10),58);assert.equal(lineupMorale(healthy[0],1),73);assert.equal(lineupMorale(healthy[0]),73);
const undone=swapLineupPlayers(swapped,healthy,{kind:'starter',index:9},{kind:'starter',index:0});
assert.deepEqual(undone,lineup);assert.equal(healthy[0].morale,73);
const outside=swapLineupPlayers(swapped,healthy,{kind:'unselected',playerId:'h24'},{kind:'starter',index:9});
assert.equal(outside.slots[9].playerId,'h24');assert.equal(lineupMorale(healthy[0]),73);assert.equal(outside.captainId,'h24');
const benches=swapLineupPlayers(lineup,healthy,{kind:'bench',index:0},{kind:'bench',index:1});
assert.equal(benches.bench[0],'h17');assert.equal(benches.bench[1],'h16');
const reverse=swapLineupPlayers(lineup,healthy,{kind:'unselected',playerId:'h25'},{kind:'bench',index:0});
assert.equal(reverse.bench[0],'h25');
const hurt=healthy.map(p=>({...p,available:p.id!=='h1'}));
const replaceHurt=swapLineupPlayers(lineup,hurt,{kind:'bench',index:0},{kind:'starter',index:0});
assert.equal(replaceHurt.slots[0].playerId,'h16');assert.ok(!replaceHurt.bench.includes('h1'));
assert.equal(swapLineupPlayers(lineup,hurt,{kind:'starter',index:0},{kind:'starter',index:1}),lineup);
assert.equal(lineupMorale({...healthy[0],morale:5},10),0);assert.equal(lineupMorale({...healthy[0],morale:5},1),5);
console.log('PASS two-click swaps in both orders, starters/bench/unselected, captain replacement, injured-player safety and reversible morale without mutating players');
